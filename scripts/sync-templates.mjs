#!/usr/bin/env node
// Sync `template-pnpm/` (canonical) to `template-npm/` and `template-yarn/`.
// Copies everything except per-PM files, then overlays files from `scripts/overlays/<pm>/`.
// Lockfiles are not synced — each variant owns its own (regenerate via `<pm> install`).
//
// Usage:
//   node scripts/sync-templates.mjs           # write
//   node scripts/sync-templates.mjs --check   # exit 1 if any variant differs from what would be written

import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
	cpSync,
	existsSync,
	mkdtempSync,
	readFileSync,
	readdirSync,
	rmSync,
	statSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(fileURLToPath(import.meta.url), "../..");
const SOURCE = join(repoRoot, "template-pnpm");
const VARIANTS = ["npm", "yarn"];
const OVERLAYS_DIR = join(repoRoot, "scripts", "overlays");

// Files/dirs in source that should NOT be copied to variants.
// Lockfiles are PM-specific; build artifacts and deps are gitignored anyway.
// Skipped both when copying from source AND when walking variants in --check mode.
// Lockfiles + .yarn/install-state are owned by the variant; build artifacts are gitignored.
const SKIP = new Set([
	"node_modules",
	"dist",
	".astro",
	"pnpm-lock.yaml",
	"package-lock.json",
	"yarn.lock",
	".yarn",
]);

const isCheck = process.argv.includes("--check");

function hashDir(dir) {
	const entries = walk(dir).sort();
	const h = createHash("sha256");
	for (const rel of entries) {
		const full = join(dir, rel);
		h.update(rel);
		h.update("\0");
		h.update(readFileSync(full));
		h.update("\0");
	}
	return h.digest("hex");
}

function walk(dir, base = dir, out = []) {
	for (const name of readdirSync(dir)) {
		if (SKIP.has(name)) continue;
		const full = join(dir, name);
		const st = statSync(full);
		if (st.isDirectory()) walk(full, base, out);
		else out.push(relative(base, full));
	}
	return out;
}

function buildVariant(pm, destDir) {
	// 1. Copy source, skipping per-PM and gitignored heavyweight dirs.
	cpSync(SOURCE, destDir, {
		recursive: true,
		filter: (src) => {
			const rel = relative(SOURCE, src);
			if (rel === "") return true;
			const top = rel.split(/[\\/]/)[0];
			return !SKIP.has(top);
		},
	});
	// 2. Apply overlay files.
	const overlay = join(OVERLAYS_DIR, pm);
	if (existsSync(overlay)) {
		cpSync(overlay, destDir, { recursive: true });
	}
}

let drift = false;

for (const pm of VARIANTS) {
	const targetName = `template-${pm}`;
	const targetDir = join(repoRoot, targetName);

	if (isCheck) {
		const tmp = mkdtempSync(join(tmpdir(), `cosmo-sync-${pm}-`));
		try {
			buildVariant(pm, tmp);
			const expected = hashDir(tmp);
			if (!existsSync(targetDir)) {
				console.error(`[sync-templates] ${targetName}/ missing — run 'node scripts/sync-templates.mjs'`);
				drift = true;
				continue;
			}
			const actual = hashDir(targetDir);
			if (actual !== expected) {
				console.error(`[sync-templates] ${targetName}/ is out of sync — run 'node scripts/sync-templates.mjs'`);
				drift = true;
			} else {
				console.log(`[sync-templates] ${targetName}/ ok`);
			}
		} finally {
			rmSync(tmp, { recursive: true, force: true });
		}
	} else {
		// Wipe everything except the PM-specific lockfile (regenerated by `<pm> install`).
		if (existsSync(targetDir)) {
			for (const name of readdirSync(targetDir)) {
				if (name === "package-lock.json" && pm === "npm") continue;
				if (name === "yarn.lock" && pm === "yarn") continue;
				if (name === "node_modules" || name === "dist" || name === ".astro") continue;
				rmSync(join(targetDir, name), { recursive: true, force: true });
			}
		}
		buildVariant(pm, targetDir);
		console.log(`[sync-templates] wrote ${targetName}/`);
	}
}

if (isCheck && drift) process.exit(1);
